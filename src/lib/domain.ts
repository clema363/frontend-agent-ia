// API types and workflow constants (columns, stages and roles).

export type Role = 'PO' | 'BA' | 'Architect' | 'DEV' | 'QA'

export type Project = {
  id: string
  key: string
  name: string
  jiraProjectKey?: string
  confluenceSpaceKey?: string
  gitlabProjectPath?: string
  memberCount: number
  // The signed-in user's roles (hats) on this project.
  myRoles: Role[]
  userStories: number
  completed: number
}

// PATCH /projects/{project_id} body: null detaches the source.
export type ProjectSources = {
  jiraConnectionId?: string | null
  jiraProjectKey?: string | null
  confluenceConnectionId?: string | null
  confluenceSpaceKey?: string | null
  gitlabConnectionId?: string | null
  gitlabProjectPath?: string | null
}

export type KanbanColumnId = 'to-author' | 'to-refine' | 'to-specify' | 'review-for-dev' | 'coding'

export type StageId = 'authoring' | 'refinement' | 'specification' | 'plan'

export type IssueType = 'Story' | 'Epic' | 'Bug' | 'Task' | 'Spike'

export type Priority = 'Low' | 'Medium' | 'High'

export type SourceTool = 'Jira' | 'Confluence' | 'GitLab'

export type Source = {
  tool: SourceTool
  label: string
}

export type ChatMessage = {
  id: string
  author: 'user' | 'agent'
  role?: Role
  text: string
}

export type StageReview = {
  decision: 'approved' | 'rejected'
  by: Role
}

// Markdown document generated by a stage agent for human approval, editing or comments.
export type StageOutput = {
  markdown: string
  sources: Source[]
  editedBy?: Role
  review?: StageReview
  chat: ChatMessage[]
}

export type CodingAgentStatus = 'queued' | 'working' | 'needs-input' | 'pr-opened' | 'merged' | 'failed'

// OpenCode steps share one session per story: the plan agent writes the plan,
// then the build agent codes it, opens the merge request and fixes its pipeline.
export type OpencodeStepId = 'plan' | 'coding'

export type StoryOpencodeSession = {
  sessionId: string
  // First message of each step, in session order.
  steps: Partial<Record<OpencodeStepId, string>>
}

// OpenCode message parts, as returned by GET /session/{id}/message (proxied by the backend).
export type OpencodeToolState = {
  status: 'pending' | 'running' | 'completed' | 'error'
  input: Record<string, unknown>
  output?: string
  error?: string
  title?: string
  metadata?: Record<string, unknown>
  time?: { start: number; end?: number }
}

type OpencodePartBase = { id: string; sessionID: string; messageID: string }

export type OpencodePart = OpencodePartBase &
  (
    | { type: 'text'; text: string; synthetic?: boolean; time?: { start: number; end?: number } }
    | { type: 'reasoning'; text: string; time: { start: number; end?: number } }
    | { type: 'tool'; callID: string; tool: string; state: OpencodeToolState }
    | { type: 'file'; mime: string; filename?: string; url: string }
    | { type: 'patch'; hash: string; files: string[] }
    | { type: 'step-start' }
    | { type: 'step-finish'; reason?: string; cost: number; tokens: OpencodeTokens }
  )

export type OpencodeTokens = { input: number; output: number; reasoning: number; cache: { read: number; write: number } }

export type OpencodeMessageInfo = {
  id: string
  sessionID: string
  role: 'user' | 'assistant'
  // Assistant messages stay open (no completed time) while OpenCode is working.
  time: { created: number; completed?: number }
  agent?: string
  // Assistant messages: the session's working directory and repository root.
  path?: { cwd: string; root: string }
  modelID?: string
  providerID?: string
  cost?: number
  tokens?: OpencodeTokens
  error?: { name: string; data?: { message?: string } }
}

export type OpencodeMessage = { info: OpencodeMessageInfo; parts: OpencodePart[] }

export type CodingAgentRun = {
  agent: string
  status: CodingAgentStatus
  startedAt: string
  branch?: string
  pullRequest?: {
    number: number
    url: string
    additions: number
    deletions: number
    ci: 'pending' | 'passed' | 'failed'
  }
  inputTokens?: number
  outputTokens?: number
  durationMs?: number
}

export type UserStory = {
  id: string
  key: string
  type: IssueType
  title: string
  priority: Priority
  projectId: string
  column: KanbanColumnId
  parentKey?: string
  // Raw requirement entered at creation, before any agent processing.
  raw: string
  contextLinks: string[]
  // A missing stage means the agent has not generated its document yet.
  stages: Partial<Record<StageId, StageOutput>>
  // Jira field values entered on the story (PUT /us/{us_id}/fields).
  fields?: Record<string, unknown>
  // Merge request and pipeline status once OpenCode starts coding.
  codingAgent?: CodingAgentRun
  // OpenCode session that writes the plan, codes it and fixes the pipeline.
  opencode?: StoryOpencodeSession
  myRoles?: Role[]
}

// POST /us body. Without force, the backend returns 409 if the requirement resembles an existing story.
export type NewStoryRequest = {
  need: string
  project: string
  priority: Priority
  force?: boolean
  issueTypeId?: string
  issueTypeName?: string
}

