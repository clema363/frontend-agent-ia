import { useState } from 'react'
import { CircleCheck, CircleDashed, Loader, RotateCw } from 'lucide-react'
import { useContextMutations, useProjectContext } from '@/api/hooks'
import { SectionHeader } from '@/components/projects/project-parts'
import { Alert, AlertDescription } from '@/components/ui/alert'
import { Button } from '@/components/ui/button'
import { Label } from '@/components/ui/label'
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs'
import { Textarea } from '@/components/ui/textarea'
import type { ContextMap, ContextMapKind, Project } from '@/lib/domain'

export function ProjectContext({ project }: { project: Project }) {
  const [tab, setTab] = useState<ContextMapKind>('overview')
  const { data: maps = [] } = useProjectContext(project.id, true)
  const validatedCount = maps.filter((map) => map.validated).length

  return (
    <div className="space-y-4">
      <SectionHeader title="Context maps" count={maps.length ? validatedCount : undefined}>
        Generated by <code className="font-mono text-xs">/init</code> from the sources. Once validated, a map is
        injected into every US produced by the agents.
      </SectionHeader>

      <Tabs value={tab} onValueChange={(value) => setTab(value as ContextMapKind)}>
        <TabsList variant="line">
          {maps.map((map) => (
            <TabsTrigger key={map.kind} value={map.kind} className="px-2">
              {map.validated ? (
                <CircleCheck className="text-green-600 dark:text-green-400" />
              ) : (
                <CircleDashed className="text-muted-foreground" />
              )}
              {map.label}
            </TabsTrigger>
          ))}
        </TabsList>
        {maps.map((map) => (
          <TabsContent key={map.kind} value={map.kind} className="pt-3 animate-in fade-in-0 duration-200">
            <MapEditor key={`${map.content}-${map.validated}`} projectId={project.id} map={map} />
          </TabsContent>
        ))}
      </Tabs>
    </div>
  )
}

type MapEditorProps = {
  projectId: string
  map: ContextMap
}

// Le brouillon reste local jusqu'à la validation, qui l'envoie au serveur.
function MapEditor({ projectId, map }: MapEditorProps) {
  const [draft, setDraft] = useState(map.content)
  const { init, validate } = useContextMutations(projectId)
  const regenerating = init.isPending
  const validated = map.validated && draft === map.content

  function regenerate() {
    // L'agent Cartographer relit les sources attachées et régénère cette carte.
    init.mutate([map.kind])
  }

  return (
    <div className="space-y-4">
      {validated ? (
        <Alert className="border-green-200 bg-green-50 text-green-900 dark:border-green-900 dark:bg-green-950/40 dark:text-green-200">
          <CircleCheck />
          <AlertDescription className="text-inherit">Map validated — injected into US production.</AlertDescription>
        </Alert>
      ) : (
        <Alert className="border-amber-200 bg-amber-50 text-amber-900 dark:border-amber-900 dark:bg-amber-950/40 dark:text-amber-200">
          <CircleDashed />
          <AlertDescription className="text-inherit">
            Draft — review it, then validate to inject it into US production.
          </AlertDescription>
        </Alert>
      )}

      <div className="space-y-1.5">
        <Label htmlFor={`map-${map.kind}`}>Content (editable)</Label>
        <Textarea
          id={`map-${map.kind}`}
          value={draft}
          disabled={regenerating}
          onChange={(event) => setDraft(event.target.value)}
          className="min-h-72 font-mono text-xs leading-relaxed"
        />
      </div>

      <div className="flex items-center justify-between gap-2">
        <Button onClick={() => validate.mutate({ kind: map.kind, content: draft })} disabled={validated || regenerating}>
          <CircleCheck data-icon="inline-start" />
          Validate
        </Button>
        <Button variant="outline" onClick={regenerate} disabled={regenerating}>
          {regenerating ? <Loader data-icon="inline-start" className="animate-spin" /> : <RotateCw data-icon="inline-start" />}
          {regenerating ? 'Regenerating…' : 'Regenerate'}
        </Button>
      </div>
    </div>
  )
}
