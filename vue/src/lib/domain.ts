// API types and workflow constants (columns, stages and roles).

export type Role = "PO" | "BA" | "Architect" | "DEV" | "QA";

export type Project = {
  id: string;
  key: string;
  name: string;
  jiraProjectKey?: string;
  confluenceSpaceKey?: string;
  gitlabProjectPath?: string;
  memberCount: number;
  // The signed-in user's roles (hats) on this project.
  myRoles: Role[];
  userStories: number;
  completed: number;
};

// PATCH /projects/{project_id} body: null detaches the source.
export type ProjectSources = {
  jiraConnectionId?: string | null;
  jiraProjectKey?: string | null;
  confluenceConnectionId?: string | null;
  confluenceSpaceKey?: string | null;
  gitlabConnectionId?: string | null;
  gitlabProjectPath?: string | null;
};

export type KanbanColumnId =
  "to-author" | "to-refine" | "to-specify" | "review-for-dev" | "sent-to-ai";

export type StageId = "authoring" | "refinement" | "specification" | "plan";

export type IssueType = "Story" | "Epic" | "Bug" | "Task" | "Spike";

export type Priority = "Low" | "Medium" | "High";

export type SourceTool = "Jira" | "Confluence" | "GitLab";

export type Source = {
  tool: SourceTool;
  label: string;
};

export type ChatMessage = {
  id: string;
  author: "user" | "agent";
  role?: Role;
  text: string;
};

export type StageReview = {
  decision: "approved" | "rejected";
  by: Role;
};

// Markdown document generated by a stage agent for human approval, editing or comments.
export type StageOutput = {
  markdown: string;
  sources: Source[];
  editedBy?: Role;
  review?: StageReview;
  chat: ChatMessage[];
};

export type CodingAgentStatus =
  "queued" | "working" | "needs-input" | "pr-opened" | "merged" | "failed";

// Activity published by the coding agent during its session, similar to Linear agent activities.
export type CodingAgentActivity = {
  id: string;
  at: string;
  kind: "thought" | "action" | "question" | "response" | "error";
  text: string;
  file?: string;
};

export type CodingAgentRun = {
  agent: string;
  status: CodingAgentStatus;
  startedAt: string;
  branch?: string;
  pullRequest?: {
    number: number;
    url: string;
    additions: number;
    deletions: number;
    ci: "pending" | "passed" | "failed";
  };
  activities: CodingAgentActivity[];
  inputTokens?: number;
  outputTokens?: number;
  durationMs?: number;
};

export type UserStory = {
  id: string;
  key: string;
  type: IssueType;
  title: string;
  priority: Priority;
  projectId: string;
  column: KanbanColumnId;
  parentKey?: string;
  // Raw requirement entered at creation, before any agent processing.
  raw: string;
  contextLinks: string[];
  // A missing stage means the agent has not generated its document yet.
  stages: Partial<Record<StageId, StageOutput>>;
  // Jira field values entered on the story (PUT /us/{us_id}/fields).
  fields?: Record<string, unknown>;
  // Coding agent session after the plan has been approved and sent.
  codingAgent?: CodingAgentRun;
  myRoles?: Role[];
};

// POST /us body. Without force, the backend returns 409 if the requirement resembles an existing story.
export type NewStoryRequest = {
  need: string;
  project: string;
  priority: Priority;
  force?: boolean;
  issueTypeId?: string;
  issueTypeName?: string;
};

export type AppUser = {
  id: string;
  name: string;
  email: string;
  isAdmin: boolean;
  isActive: boolean;
};

// Signed-in user: business role changes (PATCH /auth/me) immediately affect approval permissions.
export type Me = AppUser & {
  role: Role;
  preferences?: Record<string, unknown>;
};

export type ProjectMember = {
  userId: string;
  name: string;
  email: string;
  roles: Role[];
};

export type JiraField = {
  id: string;
  label: string;
  // Field always sent to Jira; it cannot be unchecked.
  lockedHint?: string;
};

export type JiraFieldGroup = {
  title: string;
  fields: JiraField[];
};

// GET /projects/{project_id}/jira/field-config: saved selection and catalog for display.
export type FieldConfig = {
  enabledFields: string[];
  // Mapping from cockpit priorities to Jira project priorities.
  priorityMapping: Record<string, string>;
  jiraPriorities: string[];
  catalogue: JiraFieldGroup[];
};

export type ContextMapKind = "overview" | "codebase" | "jira" | "confluence";

export type ContextMap = {
  kind: ContextMapKind;
  label: string;
  content: string;
  validated: boolean;
  // Roles allowed to approve this card.
  validatorRoles: Role[];
};

export type Connection = {
  id: string;
  siteUrl: string;
  displayName?: string;
};

export type NewConnection = {
  siteUrl: string;
  pat: string;
  displayName?: string;
};

export type JiraProject = {
  key: string;
  name: string;
};

export type ConfluencePage = {
  id: string;
  title: string;
  spaceKey: string;
};

export type IssueTypeOption = {
  id: string;
  name: string;
};

export type SuggestKind =
  "users" | "groups" | "versions" | "components" | "sprints" | "issues";

export type ConfluenceSpace = {
  key: string;
  name: string;
};

export type GitlabProject = {
  id: number;
  path: string;
};

// Default tool URLs.
export type Settings = {
  jiraUrl: string;
  confluenceUrl: string;
  gitlabUrl: string;
};

export type Health = {
  status: string;
  llmModel: string;
  llmConfigured: boolean;
};

// Duplicate prevention indicators.
export type Stats = {
  flaggedNeeds: number;
  createdDespiteWarnings: number;
  totalUs: number;
};

// Journal entry: a human action or an agent run with its usage.
export type JournalEntry = {
  id: string;
  usId: string;
  at: string;
  actor: string;
  actorType?: "user" | "agent";
  action: string;
  stage?: StageId;
  detail?: string;
  model?: string;
  inputTokens?: number;
  outputTokens?: number;
  durationMs?: number;
};

