import { useContextMutations, useProjectContext } from "@/api/hooks";
import { SectionHeader } from "@/components/projects/project-parts";
import { Alert, AlertDescription } from "@/components/ui/alert";
import { Button } from "@/components/ui/button";
import { Label } from "@/components/ui/label";
import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/components/ui/tabs";
import { Textarea } from "@/components/ui/textarea";
import type { ContextMap, ContextMapKind, Project } from "@/lib/domain";
import { CircleCheck, CircleDashed, Loader, RotateCw } from "@lucide/vue";
import { defineComponent, ref } from "vue";
export const ProjectContext = defineComponent(
  (__props: { project: Project }) => {
    const { project } = __props;
    const tab = ref<ContextMapKind>("overview");
    const setTab = (
      next: ContextMapKind | ((current: ContextMapKind) => ContextMapKind),
    ) => {
      tab.value =
        typeof next === "function"
          ? (next as (current: typeof tab.value) => typeof tab.value)(tab.value)
          : next;
    };
    const projectContextState0 = useProjectContext(
      () => project.id,
      () => true,
    );
    return () => {
      const { project } = __props;
      const { data: maps = [] } = projectContextState0;
      const validatedCount = maps.filter((map) => map.validated).length;
      return (
        <div class="space-y-4">
          <SectionHeader
            title="Context maps"
            count={maps.length ? validatedCount : undefined}
          >
            Generated by <code class="font-mono text-xs">/init</code> from the
            sources. Once validated, a map is injected into every US produced by
            the agents.
          </SectionHeader>

          <Tabs
            modelValue={tab.value}
            onUpdate:modelValue={(value) => setTab(value as ContextMapKind)}
          >
            <TabsList variant="line">
              {maps.map((map) => (
                <TabsTrigger key={map.kind} value={map.kind} class="px-2">
                  {map.validated ? (
                    <CircleCheck class="text-green-600 dark:text-green-400" />
                  ) : (
                    <CircleDashed class="text-muted-foreground" />
                  )}
                  {map.label}
                </TabsTrigger>
              ))}
            </TabsList>
            {maps.map((map) => (
              <TabsContent
                key={map.kind}
                value={map.kind}
                class="pt-3 animate-in fade-in-0 duration-200"
              >
                <MapEditor
                  key={`${map.content}-${map.validated}`}
                  projectId={project.id}
                  map={map}
                />
              </TabsContent>
            ))}
          </Tabs>
        </div>
      );
    };
  },
  { name: "ProjectContext", props: ["project"], inheritAttrs: false },
);
type MapEditorProps = {
  projectId: string;
  map: ContextMap;
};
const MapEditor = defineComponent(
  (__props: MapEditorProps) => {
    const { projectId, map } = __props;
    const draft = ref(map.content);
    const setDraft = (
      next:
        | typeof draft.value
        | ((current: typeof draft.value) => typeof draft.value),
    ) => {
      draft.value =
        typeof next === "function"
          ? (next as (current: typeof draft.value) => typeof draft.value)(
              draft.value,
            )
          : next;
    };
    const contextMutationsState1 = useContextMutations(projectId);
    return () => {
      const { map } = __props;
      const { init, validate } = contextMutationsState1;
      const regenerating = init.isLoading;
      const validated = map.validated && draft.value === map.content;
      function regenerate() {
        // The Cartographer agent reads the attached sources again and regenerates this map.
        init.trigger([map.kind]);
      }
      return (
        <div class="space-y-4">
          {validated ? (
            <Alert class="border-green-200 bg-green-50 text-green-900 dark:border-green-900 dark:bg-green-950/40 dark:text-green-200">
              <CircleCheck />
              <AlertDescription class="text-inherit">
                Map validated — injected into US production.
              </AlertDescription>
            </Alert>
          ) : (
            <Alert class="border-amber-200 bg-amber-50 text-amber-900 dark:border-amber-900 dark:bg-amber-950/40 dark:text-amber-200">
              <CircleDashed />
              <AlertDescription class="text-inherit">
                Draft — review it, then validate to inject it into US
                production.
              </AlertDescription>
            </Alert>
          )}

          <div class="space-y-1.5">
            <Label for={`map-${map.kind}`}>Content (editable)</Label>
            <Textarea
              id={`map-${map.kind}`}
              modelValue={draft.value}
              disabled={regenerating}
              onInput={(event) =>
                setDraft((event.target as HTMLInputElement).value)
              }
              class="min-h-72 font-mono text-xs leading-relaxed"
            />
          </div>

          <div class="flex items-center justify-between gap-2">
            <Button
              onClick={() =>
                validate.trigger({ kind: map.kind, content: draft.value })
              }
              disabled={validated || regenerating}
            >
              <CircleCheck data-icon="inline-start" />
              Validate
            </Button>
            <Button
              variant="outline"
              onClick={regenerate}
              disabled={regenerating}
            >
              {regenerating ? (
                <Loader data-icon="inline-start" class="animate-spin" />
              ) : (
                <RotateCw data-icon="inline-start" />
              )}
              {regenerating ? "Regenerating…" : "Regenerate"}
            </Button>
          </div>
        </div>
      );
    };
  },
  { name: "MapEditor", props: ["projectId", "map"], inheritAttrs: false },
);
